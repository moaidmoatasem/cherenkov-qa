"""Guards on the CLI's first-run surface — `--help` text and `init`'s next steps.

Both defects here come from the 2026-08-12 real-user walkthrough, and neither was
reproduced by the existing suite because nothing asserted on what a user actually
reads:

* 43 of 53 commands rendered Google-style API-doc scaffolding into `--help`
  ("Args: desktop (bool): Parameter desktop. / Returns: None: Command execution
  result."), fallout from the autogenerated-docstring sweep in `f2c1883`. The
  existing `check_cli_flags.py` gate cannot catch it — it scans `docs/` and
  `skills/` markdown, never `--help` output.
* `cherenkov init` told the user to run `./bin/cherenkov doctor`, which exits 127
  for a pip-installed user standing in a fresh project with no `bin/`.
"""

from __future__ import annotations

import re

import pytest
from click.testing import CliRunner

from cherenkov.cli.core import _register_commands, _strip_docstring_scaffolding, cli

# Matches the rendered form, i.e. what the user sees after Click indents it.
_SCAFFOLDING = re.compile(r"^\s+(Args|Arguments|Returns|Raises|Yields|Attributes):", re.MULTILINE)


@pytest.fixture(scope="module", autouse=True)
def _registered():
    _register_commands()


def _all_command_paths():
    """Every invocable path, including subcommands under the logical groups."""
    seen: set[int] = set()

    def walk(cmd, path):
        if id(cmd) in seen:
            return
        seen.add(id(cmd))
        if path:
            yield path
        for name, sub in getattr(cmd, "commands", {}).items():
            yield from walk(sub, [*path, name])

    yield from walk(cli, [])


def test_no_command_help_leaks_docstring_scaffolding():
    """The measured defect: was 43/53. Must stay 0."""
    runner = CliRunner()
    leaking = []
    for path in _all_command_paths():
        result = runner.invoke(cli, [*path, "--help"])
        if result.output and _SCAFFOLDING.search(result.output):
            leaking.append(" ".join(path))
    assert not leaking, (
        f"{len(leaking)} command(s) render API-doc scaffolding into --help: {leaking}. "
        "Help text is trimmed centrally in cherenkov/cli/core.py; a new command that "
        "bypasses _register_commands would land here."
    )


def test_commands_still_have_a_usable_summary():
    """Trimming must not strip help down to nothing."""
    runner = CliRunner()
    for name in ("doctor", "eject", "verify", "validate", "generate"):
        out = runner.invoke(cli, [name, "--help"]).output
        body = out.split("Options:")[0]
        # Something beyond the Usage: line must survive.
        assert len(body.strip().splitlines()) > 1, f"{name} lost its summary: {out!r}"


class TestStripDocstringScaffolding:
    def test_keeps_summary_and_drops_sections(self):
        text = "Do the thing.\n\nMore detail.\n\nArgs:\n    x (int): Parameter x.\n\nReturns:\n    None\n"
        assert _strip_docstring_scaffolding(text) == "Do the thing.\n\nMore detail."

    def test_text_without_scaffolding_is_untouched(self):
        text = "Just a summary.\n\nAnd a paragraph."
        assert _strip_docstring_scaffolding(text) == text

    def test_examples_are_preserved(self):
        """`Example:` blocks are worth showing, unlike Args/Returns."""
        text = "Summary.\n\nExample:\n    cherenkov verify --url http://x\n"
        assert "Example:" in (_strip_docstring_scaffolding(text) or "")

    @pytest.mark.parametrize("value", [None, ""])
    def test_empty_input_passes_through(self, value):
        assert _strip_docstring_scaffolding(value) == value

    def test_all_scaffolding_yields_none_not_empty_string(self):
        assert _strip_docstring_scaffolding("Args:\n    x (int): Parameter x.\n") is None


def test_init_next_steps_do_not_reference_a_repo_only_path(tmp_path, monkeypatch, capsys):
    """`./bin/cherenkov` exits 127 in a fresh project — the audience this text targets."""
    from cherenkov.stages.init_cmd import run_init

    monkeypatch.setattr("cherenkov.stages.init_cmd.detect_device", lambda: "CPU")
    monkeypatch.setattr("cherenkov.stages.init_cmd.detect_ollama", lambda: (False, "Ollama is not running"))
    monkeypatch.chdir(tmp_path)
    run_init()
    out = capsys.readouterr().out

    assert "./bin/cherenkov" not in out, out
    assert "cherenkov doctor" in out

    # The no-spec branch used to print `doctor` twice: once as "Run:", again as
    # "Then:", giving the user no actual next step.
    next_steps = out.split("Next steps:", 1)[-1]
    assert next_steps.count("cherenkov doctor") == 1, next_steps
