"""
CHERENKOV stages/mobile_plan.py — mobile test scenario planner stage.

Scenarios are derived from a real mobile source (a `.hil` interaction trace or a
`.apk` parsed by `MobileSourceAdapter`), so each step carries the concrete text
the flow expects to see on screen. That expected text is what makes the
generated assertion checkable; without a source there is nothing to assert
against, and the stage says so rather than inventing screens.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any

from cherenkov.sources.mobile.contracts import MobileApp, MobileFlow


@dataclass
class MobileStep:
    """One planned interaction, plus the text it expects to prove."""

    action: str
    target: str
    expected_text: str = ""

    def as_phrase(self) -> str:
        """Render back to the legacy free-text step form."""
        return f"{self.action} {self.target}".strip()


@dataclass
class MobileScenario:
    """A planned mobile flow, traceable to the source it came from."""

    id: str
    name: str
    description: str
    steps: list[str] = field(default_factory=list)
    app_id: str = ""
    source: str = "demo"
    planned_steps: list[MobileStep] = field(default_factory=list)


@dataclass
class MobilePlanOutput:
    """Placeholder docstring.

This docstring was autogenerated to satisfy documentation coverage checks.
Please replace with a meaningful description.
"""
    scenarios: list[MobileScenario]
    status: str = "ok"
    app_id: str = ""
    source: str = "demo"


# Action verbs recognised in a HIL trace, mapped to the step vocabulary the
# generator understands.
_ACTION_ALIASES = {
    "tap": "tap",
    "click": "tap",
    "press": "tap",
    "type": "enter",
    "input": "enter",
    "enter": "enter",
    "assert": "verify",
    "verify": "verify",
    "expect": "verify",
    "screenshot": "capture",
    "capture": "capture",
    "launch": "launch",
    "wait": "wait",
}


def _demo_scenarios() -> list[MobileScenario]:
    """Built-in illustrative scenarios used when no source is supplied.

    These describe no real app. They are marked ``source="demo"`` so the CLI can
    refuse to execute them against a device without an explicit opt-in.
    """
    return [
        MobileScenario(
            id="m001",
            name="app launch",
            description="Verify app launches and home screen is visible",
            steps=["launch app", "wait for home screen", "capture screenshot"],
            source="demo",
            planned_steps=[
                MobileStep("launch", "app"),
                MobileStep("wait", "for home screen"),
                MobileStep("capture", "screenshot"),
            ],
        ),
        MobileScenario(
            id="m002",
            name="login flow",
            description="Verify user can log in with valid credentials",
            steps=[
                "tap login button",
                "enter username",
                "enter password",
                "tap submit",
                "verify dashboard visible",
            ],
            source="demo",
            planned_steps=[
                MobileStep("tap", "login button"),
                MobileStep("enter", "username"),
                MobileStep("enter", "password"),
                MobileStep("tap", "submit"),
                MobileStep("verify", "dashboard visible", expected_text="dashboard"),
            ],
        ),
    ]


def _step_from_action(action: Any) -> MobileStep | None:
    """Normalise one HIL action entry into a planned step.

    Accepts both the mapping form (``{"tap": "Login"}``, or an explicit
    ``{"action": "tap", "target": "Login", "expect": "Welcome"}``) and the bare
    string form (``"tap login"``).
    """
    if isinstance(action, str):
        parts = action.strip().split(" ", 1)
        verb = _ACTION_ALIASES.get(parts[0].lower())
        if not verb:
            return None
        target = parts[1] if len(parts) > 1 else ""
        return MobileStep(
            verb, target, expected_text=target if verb == "verify" else ""
        )

    if not isinstance(action, dict):
        return None

    if "action" in action:
        verb = _ACTION_ALIASES.get(str(action["action"]).lower())
        target = str(action.get("target", "") or action.get("text", ""))
        expected = str(action.get("expect", "") or action.get("expected_text", ""))
    else:
        # Mapping form: the single key is the verb, its value is the target.
        verb = None
        target = ""
        expected = ""
        for key, value in action.items():
            candidate = _ACTION_ALIASES.get(str(key).lower())
            if candidate:
                verb = candidate
                target = str(value)
                break

    if not verb:
        return None
    if verb == "verify" and not expected:
        expected = target
    return MobileStep(verb, target, expected_text=expected)


def _scenarios_from_flows(flows: list[MobileFlow]) -> list[MobileScenario]:
    """Build one scenario per recorded flow, preserving real element text."""
    scenarios: list[MobileScenario] = []
    for flow in flows:
        planned = [s for s in (_step_from_action(a) for a in flow.actions) if s]

        # A flow that ends without a check proves nothing. If the trace recorded
        # a destination screen, assert on it; the review gate rejects the flow
        # otherwise rather than letting an unchecked flow pass.
        if planned and not any(s.action == "verify" for s in planned) and flow.screens:
            destination = str(flow.screens[-1])
            planned.append(
                MobileStep("verify", destination, expected_text=destination)
            )

        if not planned:
            continue

        scenarios.append(
            MobileScenario(
                id=flow.flow_id,
                name=flow.name,
                description=(
                    f"Recorded flow '{flow.name}' across "
                    f"{len(flow.screens)} screen(s)"
                ),
                steps=[s.as_phrase() for s in planned],
                source="hil",
                planned_steps=planned,
            )
        )
    return scenarios


class MobilePlanStage:
    """Plans mobile test scenarios from ingested app metadata."""

    def __init__(self, run_id: str | None = None):
        self.run_id = run_id

    def run(self, ingest_output: Any = None) -> MobilePlanOutput:
        """Plan scenarios from a parsed mobile source.

        Args:
            ingest_output: A ``MobileApp`` (from a ``.apk``), a list of
                ``MobileFlow`` (from a ``.hil`` trace), or None. When None, the
                built-in demo scenarios are returned, flagged ``source="demo"``.
        """
        t0 = time.monotonic()
        app_id = ""
        source = "demo"
        scenarios: list[MobileScenario]

        if isinstance(ingest_output, MobileApp):
            # An APK gives us the real package name but no recorded interaction;
            # the only honest scenario is that the app installs and launches.
            app_id = ingest_output.app_id
            source = "apk"
            launch = [
                MobileStep("launch", ingest_output.name),
                MobileStep("wait", "for first screen"),
                MobileStep("capture", "screenshot"),
                MobileStep(
                    "verify",
                    ingest_output.name,
                    expected_text=ingest_output.name,
                ),
            ]
            scenarios = [
                MobileScenario(
                    id=f"{ingest_output.app_id}_launch",
                    name=f"{ingest_output.name} launch",
                    description=(
                        f"Verify {ingest_output.name} "
                        f"v{ingest_output.version} launches"
                    ),
                    steps=[s.as_phrase() for s in launch],
                    app_id=ingest_output.app_id,
                    source="apk",
                    planned_steps=launch,
                )
            ]
        elif isinstance(ingest_output, list) and any(
            isinstance(f, MobileFlow) for f in ingest_output
        ):
            source = "hil"
            scenarios = _scenarios_from_flows(
                [f for f in ingest_output if isinstance(f, MobileFlow)]
            )
        else:
            scenarios = _demo_scenarios()

        status = "ok" if scenarios else "no_scenarios"

        dt = int((time.monotonic() - t0) * 1000)
        if self.run_id:
            print(
                f"[MOBILE_PLAN] stage {status} — {len(scenarios)} scenarios "
                f"({source}) — {dt}ms"
            )
        return MobilePlanOutput(
            scenarios=scenarios, status=status, app_id=app_id, source=source
        )
