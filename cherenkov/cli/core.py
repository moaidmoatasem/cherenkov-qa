def _get_version() -> str:
    try:
        from importlib.metadata import version, PackageNotFoundError
        try:
            return version("cherenkov-qa")
        except PackageNotFoundError:
            pass
        try:
            return version("cherenkov")
        except PackageNotFoundError:
            pass
    except ImportError:
        pass
    return "dev"


@click.group(cls=TieredGroup, invoke_without_command=True)
@click.version_option(version=_get_version(), prog_name="cherenkov")
@click.pass_context
def cli(ctx):
    """Cherenkov — the integrity gate for AI-written tests.

    Before you merge an AI agent's change to your tests, prove they still
    catch bugs. Start with: cherenkov demo, then cherenkov check.

Args:
    ctx: Click context object passed by click.pass_context.

Returns:
    None: Command execution result.
    """
    if ctx.invoked_subcommand is None:
        click.echo(ctx.get_help())



