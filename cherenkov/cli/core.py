# Google-style API-doc sections. These belong in generated API reference, not in
# `--help`: 43 of 53 commands were rendering blocks like "Args: desktop (bool):
# Parameter desktop. / Returns: None: Command execution result." into the CLI's
# primary discoverability surface, saying nothing a user needs. `Example(s):` is
# deliberately absent — those are worth showing.
_DOCSTRING_SCAFFOLDING = re.compile(
    r"^[ \t]*(?:Args|Arguments|Returns|Raises|Yields|Attributes)[ \t]*:[ \t]*$",
    re.MULTILINE,
)


def _strip_docstring_scaffolding(text: str | None) -> str | None:
    """Trim a help string at the first API-doc section heading.

    Docstrings here put the human summary first and the scaffolding last, so
    truncating at the first heading keeps everything a reader wants and drops
    what the autogenerated-docstring sweep added.
    """
    if not text:
        return text
    match = _DOCSTRING_SCAFFOLDING.search(text)
    if not match:
        return text
    return text[: match.start()].rstrip() or None


def _clean_help_recursively(command: click.Command, _seen: set[int] | None = None) -> None:
    """Apply the trim to a command and every subcommand it exposes."""
    _seen = _seen if _seen is not None else set()
    if id(command) in _seen:  # groups share command objects with top-level aliases
        return
    _seen.add(id(command))
    command.help = _strip_docstring_scaffolding(command.help)
    for sub in getattr(command, "commands", {}).values():
        _clean_help_recursively(sub, _seen)

