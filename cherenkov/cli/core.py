@click.command("labs")
def labs_cmd() -> None:
    """List experimental (Labs) commands.

    They stay fully callable, but are outside the integrity-gate product and
    frozen for new features.
    """
    ctx = click.get_current_context()
    root = ctx.find_root().command
    assert isinstance(root, click.Group)  # the root CLI is always a group
    for name in labs_names(root):
        cmd = root.get_command(ctx, name)
        click.echo(f"  {name:<14} {cmd.get_short_help_str(limit=60) if cmd else ''}")


def main():
    """Main CLI entry point executing legacy command rewriting and Click command invocation.

    Returns:
        None
    """
    # Legacy bare invocation: `cherenkov --spec foo.yaml` → `cherenkov validate --spec foo.yaml`
    if len(sys.argv) > 1 and sys.argv[1].startswith("-") and "--spec" in sys.argv[1:]:
        sys.argv.insert(1, "validate")
    _register_commands()
    cli()


if __name__ == "__main__":
    main()
